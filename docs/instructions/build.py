def register_fonts() -> None:
    for name, file in [("Inter", "Inter-Regular.ttf"), ("Inter-Medium", "Inter-Medium.ttf"),
                       ("Inter-SemiBold", "Inter-SemiBold.ttf"), ("Inter-Bold", "Inter-Bold.ttf")]:
        pdfmetrics.registerFont(TTFont(name, str(FONTS / file)))
    pdfmetrics.registerFontFamily("Inter", normal="Inter", bold="Inter-SemiBold", italic="Inter", boldItalic="Inter-Bold")


def styles() -> dict[str, ParagraphStyle]:
    base = ParagraphStyle("base", fontName="Inter", fontSize=10.5, leading=15.5, textColor=INK, alignment=TA_LEFT)
    return {
        "body": base,
        "muted": ParagraphStyle("muted", parent=base, textColor=INK2, fontSize=9.5, leading=13.5),
        "small": ParagraphStyle("small", parent=base, textColor=MUTED, fontSize=8.5, leading=12),
        "title": ParagraphStyle("title", parent=base, fontName="Inter-Bold", fontSize=26, leading=31, spaceAfter=6),
        "lead": ParagraphStyle("lead", parent=base, fontSize=12, leading=18, textColor=INK2, spaceAfter=10),
        "h2": ParagraphStyle("h2", parent=base, fontName="Inter-Bold", fontSize=15.5, leading=20,
                             spaceBefore=14, spaceAfter=6),
        "h3": ParagraphStyle("h3", parent=base, fontName="Inter-SemiBold", fontSize=11.5, leading=16,
                             spaceBefore=8, spaceAfter=3),
        "step": ParagraphStyle("step", parent=base, leftIndent=0),
        "bubble": ParagraphStyle("bubble", parent=base, fontSize=9.5, leading=13.5),
        "button": ParagraphStyle("button", parent=base, fontName="Inter-Medium", fontSize=8.5, leading=11,
                                 textColor=ACCENT, alignment=1),
        "caption": ParagraphStyle("caption", parent=base, fontSize=8.5, leading=12, textColor=MUTED, alignment=1),
        "cell": ParagraphStyle("cell", parent=base, fontSize=9.5, leading=13),
        "cellh": ParagraphStyle("cellh", parent=base, fontName="Inter-SemiBold", fontSize=8.5, leading=11.5,
                                textColor=INK2),
    }


S: dict[str, ParagraphStyle] = {}


# --- строительные блоки ---


def p(text: str, style: str = "body") -> Paragraph:
    return Paragraph(text, S[style])


def h2(text: str) -> list:
    return [CondPageBreak(45 * mm), p(text, "h2")]


def h3(text: str) -> Paragraph:
    return p(text, "h3")


def gap(h: float = 4) -> Spacer:
    return Spacer(1, h * mm)


def bullets(items: list[str], style: str = "body") -> Table:
    rows = [[Paragraph("●", ParagraphStyle("dot", parent=S["body"], textColor=ACCENT, fontSize=7, leading=15.5)),
             p(t, style)] for t in items]
    t = Table(rows, colWidths=[5 * mm, CONTENT_W - 5 * mm])
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0),
                           ("RIGHTPADDING", (0, 0), (-1, -1), 0), ("TOPPADDING", (0, 0), (-1, -1), 1),
                           ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
    return t


def steps(items: list[str]) -> Table:
    """Нумерованные шаги с синими кружками."""
    num_style = ParagraphStyle("num", parent=S["body"], fontName="Inter-Bold", fontSize=9, leading=11,
                               textColor=colors.white, alignment=1)
    rows = []
    for i, text in enumerate(items, start=1):
        badge = Table([[Paragraph(str(i), num_style)]], colWidths=[6 * mm], rowHeights=[6 * mm])
        badge.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), ACCENT), ("ROUNDEDCORNERS", [3 * mm] * 4),
                                   ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("TOPPADDING", (0, 0), (-1, -1), 0),
                                   ("BOTTOMPADDING", (0, 0), (-1, -1), 1.2)]))
        rows.append([badge, p(text)])
    t = Table(rows, colWidths=[9 * mm, CONTENT_W - 9 * mm])
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0),
                           ("RIGHTPADDING", (0, 0), (-1, -1), 0), ("TOPPADDING", (0, 0), (-1, -1), 2),
                           ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]))
    return t


def callout(text: str, kind: str = "tip") -> Table:
    bg, bar, title = {
        "tip": (ACCENT_SOFT, ACCENT, "Совет"),
        "warn": (WARN_BG, colors.HexColor("#E8901A"), "Важно"),
        "ok": (GOOD_BG, colors.HexColor("#1F9D55"), "Хорошо знать"),
    }[kind]
    t = Table([[p(f"<b>{title}.</b> {text}", "muted")]], colWidths=[CONTENT_W])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), bg), ("LINEBEFORE", (0, 0), (0, -1), 3, bar),
                           ("LEFTPADDING", (0, 0), (-1, -1), 10), ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                           ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 8)]))
    return KeepTogether([gap(1.5), t, gap(2)])


def bot_message(text: str, buttons: list[list[str]] | None = None, *, width: float = 120 * mm,
                caption: str | None = None) -> KeepTogether:
    """Похожее на MAX сообщение бота с кнопками под ним."""
    bubble = Table([[p(text, "bubble")]], colWidths=[width])
    bubble.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), BUBBLE), ("ROUNDEDCORNERS", [4 * mm] * 4),
                                ("LEFTPADDING", (0, 0), (-1, -1), 10), ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                                ("TOPPADDING", (0, 0), (-1, -1), 8), ("BOTTOMPADDING", (0, 0), (-1, -1), 9)]))
    parts = [bubble]
    for row in buttons or []:
        cells = [p(b, "button") for b in row]
        bw = (width - (len(row) - 1) * 2 * mm) / len(row)
        btn = Table([cells], colWidths=[bw] * len(row), rowHeights=[8.5 * mm])
        st = [("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("TOPPADDING", (0, 0), (-1, -1), 0),
              ("BOTTOMPADDING", (0, 0), (-1, -1), 1)]
        btn.setStyle(TableStyle(st))
        # Каждая кнопка — отдельная скруглённая «плашка»
        wrapped = []
        for c in cells:
            one = Table([[c]], colWidths=[bw], rowHeights=[8.5 * mm])
            one.setStyle(TableStyle(st + [("BACKGROUND", (0, 0), (-1, -1), ACCENT_SOFT),
                                          ("ROUNDEDCORNERS", [2.5 * mm] * 4)]))
            wrapped.append(one)
        line = Table([wrapped], colWidths=[bw + (2 * mm if i < len(row) - 1 else 0) for i in range(len(row))])
        line.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                                  ("TOPPADDING", (0, 0), (-1, -1), 1.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))
        parts.append(line)
    outer = Table([[x] for x in parts], colWidths=[width])
    outer.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                               ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))
    outer.hAlign = "LEFT"
    items = [gap(1.5), outer]
    if caption:
        items += [gap(1), p(caption, "small")]
    return KeepTogether(items + [gap(3)])


def screenshot(name: str, caption: str, width: float = CONTENT_W) -> KeepTogether:
    path = IMG / name
    from reportlab.lib.utils import ImageReader

    iw, ih = ImageReader(str(path)).getSize()
    w = min(width, CONTENT_W)
    h = w * ih / iw
    if h > 150 * mm:  # высокие окна — уже, чтобы помещались на страницу
        h = 150 * mm
        w = h * iw / ih
    img = Image(str(path), width=w, height=h)
    frame = Table([[img]], colWidths=[w + 2])
    frame.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.6, LINE), ("ROUNDEDCORNERS", [2 * mm] * 4),
                               ("LEFTPADDING", (0, 0), (-1, -1), 1), ("RIGHTPADDING", (0, 0), (-1, -1), 1),
                               ("TOPPADDING", (0, 0), (-1, -1), 1), ("BOTTOMPADDING", (0, 0), (-1, -1), 1)]))
    return KeepTogether([gap(2), frame, gap(1.5), p(caption, "caption"), gap(3)])


def table(head: list[str], rows: list[list[str]], widths: list[float]) -> Table:
    data = [[p(h, "cellh") for h in head]] + [[p(c, "cell") for c in r] for r in rows]
    t = Table(data, colWidths=[w * CONTENT_W for w in widths], repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BUBBLE), ("LINEBELOW", (0, 1), (-1, -1), 0.5, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6), ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6), ("ROUNDEDCORNERS", [2 * mm] * 4),
    ]))
    return t


def link(url: str) -> str:
    return f'<link href="{url}"><font color="#2F6CB3"><u>{url}</u></font></link>'


# --- обложка, колонтитулы ---


def make_doc(path: Path, audience: str, title: str):
    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=MARGIN, rightMargin=MARGIN,
                            topMargin=24 * mm, bottomMargin=18 * mm, title=title,
                            author="Диспетчерская", subject=audience)

    def decorate(canvas, d):
        canvas.saveState()
        canvas.drawImage(str(LOGO), MARGIN, PAGE_H - 15 * mm, width=6.4 * mm, height=6.8 * mm, mask="auto")
        canvas.setFont("Inter-SemiBold", 9)
        canvas.setFillColor(INK)
        canvas.drawString(MARGIN + 9 * mm, PAGE_H - 12.3 * mm, "Диспетчерская")
        canvas.setFont("Inter", 9)
        canvas.setFillColor(MUTED)
        canvas.drawRightString(PAGE_W - MARGIN, PAGE_H - 12.3 * mm, audience)
        canvas.setStrokeColor(LINE)
        canvas.setLineWidth(0.6)
        canvas.line(MARGIN, PAGE_H - 17 * mm, PAGE_W - MARGIN, PAGE_H - 17 * mm)
        # Тонкая полоска фирменного градиента сверху
        steps_n = 60
        for i in range(steps_n):
            t = i / (steps_n - 1)
            c = colors.Color(0.333 + (0.333 - 0.333) * t, 0.553 + (0.714 - 0.553) * t, 0.792 + (0.773 - 0.792) * t)
            canvas.setFillColor(c)
            canvas.rect(i * PAGE_W / steps_n, PAGE_H - 2.2 * mm, PAGE_W / steps_n + 0.5, 2.2 * mm, stroke=0, fill=1)
        canvas.setFont("Inter", 8.5)
        canvas.setFillColor(MUTED)
        canvas.drawString(MARGIN, 10 * mm, f"Версия от {date.today():%d.%m.%Y}")
        canvas.drawRightString(PAGE_W - MARGIN, 10 * mm, f"Страница {d.page}")
        canvas.restoreState()

    return doc, decorate


def cover(title: str, lead: str) -> list:
    return [gap(6), p(title, "title"), p(lead, "lead"), gap(2)]


def contents(items: list[str]) -> Table:
    t = Table([[p("<b>Содержание</b>", "muted")]] + [[p(f"{i}. {x}", "muted")] for i, x in enumerate(items, 1)],
              colWidths=[CONTENT_W])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), BUBBLE), ("ROUNDEDCORNERS", [3 * mm] * 4),
                           ("LEFTPADDING", (0, 0), (-1, -1), 12), ("TOPPADDING", (0, 0), (0, 0), 9),
                           ("BOTTOMPADDING", (0, -1), (-1, -1), 10), ("TOPPADDING", (0, 1), (-1, -1), 1),
                           ("BOTTOMPADDING", (0, 0), (-1, -2), 1)]))
    return t


